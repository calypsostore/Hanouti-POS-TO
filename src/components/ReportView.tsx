import { useRef, useState } from 'react';
import { Button } from './Button';
import { formatTnd } from '../lib/format';
import type { ReportRecord } from '../types/domain';
import { printOrSharePdf } from '../services/receiptExport';

const money = (amount: number | undefined) => `${formatTnd((amount ?? 0) / 1000)} DT`;

export function ReportView({ report, storeName, onClose }: { report: ReportRecord; storeName: string; onClose: () => void }) {
  const [shareError, setShareError] = useState('');
  const printTarget = useRef<HTMLElement>(null);
  const reportStoreName = report.storeName ?? storeName;
  const lines = [
    reportStoreName,
    report.type === 'X' ? 'X REPORT — NOT A CLOSE' : 'Z REPORT — DAY CLOSED',
    `Business date: ${report.businessDate}`,
    `Period: ${report.periodFrom ? new Date(report.periodFrom).toLocaleString() : '—'} to ${report.periodTo ? new Date(report.periodTo).toLocaleString() : new Date(report.createdAt).toLocaleString()}`,
    `Generated by: ${report.generatedBy ?? 'Owner'}`,
    `Sales: ${money(report.salesMillimes)}`,
    `Orders: ${report.orderCount}`,
    `Expected cash: ${money(report.totalExpectedCashMillimes)}`,
    `Counted cash: ${money(report.totalCountedMillimes)}`,
    `Difference: ${money(report.totalDifferenceMillimes ?? report.cashDifferenceMillimes)}`,
    'Sales by category:',
    ...(report.salesByCategory ?? []).map((item) => `${item.name}: ${item.quantity} units, ${money(item.totalMillimes)}`),
    'Items sold:',
    ...(report.itemsSold ?? []).map((item) => `${item.quantity} x ${item.name}: ${money(item.totalMillimes)}`),
    'Payment split:',
    ...Object.entries(report.paymentSplit ?? {}).map(([method, total]) => `${method}: ${money(total)}`),
    `Voids (${report.voids?.count ?? 0}), total ${money(report.voids?.totalMillimes)}:`,
    ...(report.voids?.orders ?? []).map((item) => `Ticket #${item.ticketNumber}: ${item.reason} (${money(item.totalMillimes)})`),
    'Shifts:',
    ...(report.shifts ?? []).map((shift) => {
      if (shift.status === 'in_progress') return `${shift.staffName}, in progress, opened ${new Date(shift.openedAt).toLocaleString()}`;
      return `${shift.staffName}, opened ${new Date(shift.openedAt).toLocaleString()}, closed ${shift.closedAt ? new Date(shift.closedAt).toLocaleString() : '—'}, expected ${money(shift.expectedCashMillimes)}, counted ${shift.countedCashMillimes === undefined ? '—' : money(shift.countedCashMillimes)}, difference ${shift.differenceMillimes === undefined ? '—' : money(shift.differenceMillimes)}${shift.forceClosedByOwner ? ' (force closed by owner)' : ''}${shift.voidAdjustmentMillimes ? `, Void adjustment ${money(shift.voidAdjustmentMillimes)}` : ''}`;
    }),
    `Tabs issued: ${money(report.tabsIssuedMillimes)}`,
    `Tabs settled: ${money(report.tabsSettledMillimes)}`,
    `Outstanding tabs: ${money(report.tabsOutstandingMillimes)}`,
    `Z number: ${report.zNumber ?? '—'}`,
  ].join('\n');

  async function shareText() {
    setShareError('');
    try {
      if (navigator.share) await navigator.share({ title: `${report.type} report`, text: lines });
      else if (navigator.clipboard) await navigator.clipboard.writeText(lines);
      else throw new Error('Sharing is not available in this browser.');
    } catch (error) {
      if (error instanceof Error && error.name === 'AbortError') return;
      setShareError(error instanceof Error ? error.message : 'Unable to share this report.');
    }
  }

  async function printReport() {
    setShareError('');
    try {
      await printOrSharePdf(printTarget.current, `${report.type.toLowerCase()}-report-${report.businessDate}`, `${report.type} report`);
    } catch (error) {
      if (error instanceof Error && error.name === 'AbortError') return;
      setShareError(error instanceof Error ? error.message : 'Unable to create or share this report.');
    }
  }

  return (
    <div className="receipt-overlay" onMouseDown={onClose}>
      <section role="dialog" aria-modal="true" aria-label={`${report.type} report`} className="receipt-dialog" onMouseDown={(event) => event.stopPropagation()}>
        <div className="receipt-actions no-print">
          <Button variant="secondary" onClick={() => { void printReport(); }}>Print / Save PDF</Button>
          <Button variant="secondary" onClick={() => { void shareText(); }}>Share text</Button>
          <Button variant="ghost" onClick={onClose}>Close</Button>
        </div>
        {shareError && <p role="alert" className="no-print receipt-error">{shareError}</p>}
        <article ref={printTarget} className="receipt-print-target thermal-receipt">
          <header className="receipt-center">
            <strong>{reportStoreName}</strong>
            <strong>{report.type === 'X' ? 'X REPORT — NOT A CLOSE' : 'Z REPORT — DAY CLOSED'}</strong>
            <div>Business date: {report.businessDate}</div>
            <div>From: {report.periodFrom ? new Date(report.periodFrom).toLocaleString() : '—'}</div>
            <div>To: {report.periodTo ? new Date(report.periodTo).toLocaleString() : new Date(report.createdAt).toLocaleString()}</div>
            <div>Generated by: {report.generatedBy ?? 'Owner'}</div>
          </header>
          <Rule />
          <ReceiptRow label="Sales" amount={money(report.salesMillimes)} />
          <ReceiptRow label="Orders" amount={String(report.orderCount)} />
          <ReceiptRow label="Expected cash" amount={money(report.totalExpectedCashMillimes)} />
          <ReceiptRow label="Counted cash" amount={money(report.totalCountedMillimes)} />
          <ReceiptRow label="Difference" amount={money(report.totalDifferenceMillimes ?? report.cashDifferenceMillimes)} />
          <Rule />
          <strong>SALES BY CATEGORY</strong>
          {(report.salesByCategory ?? []).map((item) => <ReceiptRow key={item.categoryId} label={`${item.name} (${item.quantity})`} amount={money(item.totalMillimes)} />)}
          <Rule />
          <strong>ITEMS SOLD</strong>
          {(report.itemsSold ?? []).map((item) => <ReceiptRow key={item.itemId} label={`${item.quantity} × ${item.name}`} amount={money(item.totalMillimes)} />)}
          <Rule />
          <strong>PAYMENT SPLIT</strong>
          {Object.entries(report.paymentSplit ?? {}).map(([method, total]) => <ReceiptRow key={method} label={method.toUpperCase()} amount={money(total)} />)}
          <Rule />
          <strong>VOIDS ({report.voids?.count ?? 0})</strong>
          <ReceiptRow label="Void total" amount={money(report.voids?.totalMillimes)} />
          {(report.voids?.orders ?? []).map((item) => (
            <div className="receipt-item" key={`${item.ticketNumber}-${item.reason}`}>
              <div>Ticket #{item.ticketNumber} • {money(item.totalMillimes)}</div>
              <div>{item.reason || 'No reason recorded'}</div>
            </div>
          ))}
          <Rule />
          <strong>SHIFTS</strong>
          {(report.shifts ?? []).map((shift) => (
            <div className="receipt-item" key={shift.shiftId}>
              <strong>{shift.staffName}{shift.forceClosedByOwner ? ' • force closed by owner' : ''}</strong>
              <div>Opened: {new Date(shift.openedAt).toLocaleString()}</div>
              {shift.status === 'in_progress' ? <strong>In progress</strong> : (
                <>
                  <div>Closed: {shift.closedAt ? new Date(shift.closedAt).toLocaleString() : '—'}</div>
                  <ReceiptRow label="Start" amount={money(shift.startingCashMillimes)} />
                  <ReceiptRow label="Expected" amount={money(shift.expectedCashMillimes)} />
                  <ReceiptRow label="Counted" amount={shift.countedCashMillimes === undefined ? '—' : money(shift.countedCashMillimes)} />
                  <ReceiptRow label="Difference" amount={shift.differenceMillimes === undefined ? '—' : money(shift.differenceMillimes)} />
                </>
              )}
              {shift.voidAdjustmentMillimes !== undefined && <ReceiptRow label="Void adjustment" amount={money(shift.voidAdjustmentMillimes)} />}
            </div>
          ))}
          <Rule />
          <ReceiptRow label="Tabs issued" amount={money(report.tabsIssuedMillimes)} />
          <ReceiptRow label="Tabs settled" amount={money(report.tabsSettledMillimes)} />
          <ReceiptRow label="Outstanding tabs" amount={money(report.tabsOutstandingMillimes)} />
          <Rule />
          <footer className="receipt-center">
            <strong>{report.type === 'Z' ? `Z NUMBER ${report.zNumber ?? '—'}` : 'X REPORT — NOT A CLOSE'}</strong>
            <div>{new Date(report.createdAt).toLocaleString()}</div>
          </footer>
        </article>
      </section>
    </div>
  );
}

function ReceiptRow({ label, amount }: { label: string; amount: string }) {
  return <div className="receipt-row"><span>{label}</span><strong>{amount}</strong></div>;
}

function Rule() {
  return <div className="receipt-rule" />;
}
